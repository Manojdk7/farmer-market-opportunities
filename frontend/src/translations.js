export function getLocalizedDistrictName(districtName, lang = 'kn') {
  if (!districtName) return ''
  const item = KARNATAKA_DISTRICTS.find(d => 
    d.name.toLowerCase() === districtName.toLowerCase() || d.name_kn === districtName
  )
  if (!item) return districtName
  return lang === 'kn' ? item.name_kn : item.name
}

export function getLocalizedCropName(cropName, lang = 'kn') {
  if (!cropName) return ''
  const item = KARNATAKA_CROPS.find(c => 
    c.name.toLowerCase() === cropName.toLowerCase() || 
    c.name_kn === cropName || 
    c.agmarknet_name.toLowerCase() === cropName.toLowerCase() ||
    c.key.toLowerCase() === cropName.toLowerCase()
  )
  if (!item) return cropName
  return lang === 'kn' ? item.name_kn : item.name
}

export function getLocalizedMarketName(name, lang = 'kn') {
  if (!name) return ''
  // Clean APMC suffix for natural Kannada display if needed
  if (lang === 'kn') {
    if (name.includes('APMC')) {
      const base = name.replace(/\s*APMC\s*/i, '').trim()
      return `${base} ಎಪಿಎಂಸಿ`
    }
    return name
  }
  return name
}

export function t(key, lang = 'kn', params = {}) {
  const dict = translations[lang] || translations.kn
  let text = dict[key] || translations.kn[key] || key
  for (const [pKey, pVal] of Object.entries(params)) {
    text = text.replace(new RegExp(`\\{${pKey}\\}`, 'g'), pVal)
  }
  return text
}
